"""ApplyMe: find internships and co-ops.

Commands (run in this folder):
    python applyme.py ingest              download new postings, score the top ones, write the report
                                          (add --no-ai to skip the Claude scoring step)
    python applyme.py rank                score the top in-scope roles again (only new/changed ones cost money)
                                          options: --dry-run (free: rules + page download only), --limit 5
    python applyme.py report              rebuild the report from the database (no downloading, no AI)
    python applyme.py letter 123          write a cover-letter DRAFT for posting #123 (asks you first)
    python applyme.py add <url>           add a posting you found yourself (Handshake, LinkedIn, Indeed...)
    python applyme.py spend               show how much of the API budget is used
    python applyme.py browser             start the ApplyMe Chrome window (sign in to Google there once)
    python applyme.py open 5              fill the top 5 unapplied roles in Chrome tabs, STOPPING BEFORE SUBMIT
                                          options: --dry-run (just show the answers), --refill, --include-unsupported
    python applyme.py approve 123         approve the cover-letter draft of #123 so autofill may attach it
    python applyme.py answers             list saved form answers; answers fix 7 "new answer" corrects #7
    python applyme.py verify              re-check which companies in companies.txt have a public job feed
    python applyme.py mark 123 applied    set the status of posting #123 (new, saved, ready_to_review,
                                          applied, interview, rejected, offer, skipped)
"""
import json
import sys
import webbrowser
from datetime import date, timedelta
from pathlib import Path

import yaml

import budget
import db
import fetch
import filters
import letters
import rank
import report
import sources

HERE = Path(__file__).resolve().parent
BOARDS_FILE = HERE / "company_boards.yaml"
RECHECK_DAYS = 7


def load_config():
    if not (HERE / "config.yaml").exists():
        sys.exit("config.yaml not found. Copy config.example.yaml to config.yaml and edit it.")
    cfg = yaml.safe_load((HERE / "config.yaml").read_text(encoding="utf-8"))
    if cfg.get("auto_submit") or cfg.get("tracking", {}).get("mark_applied_automatically"):
        sys.exit("config.yaml: auto_submit and mark_applied_automatically must stay false.")
    return cfg


def company_names():
    lines = (HERE / "companies.txt").read_text(encoding="utf-8").splitlines()
    return [l.strip() for l in lines if l.strip() and not l.strip().startswith("#")]


def load_boards(force=False):
    """Which public job board each company uses. Cached in company_boards.yaml, rechecked weekly."""
    boards = {}
    if BOARDS_FILE.exists():
        boards = yaml.safe_load(BOARDS_FILE.read_text(encoding="utf-8")) or {}
    names = company_names()
    stale = (date.today() - timedelta(days=RECHECK_DAYS)).isoformat()
    todo = [n for n in names if force or n not in boards or str(boards[n].get("checked", "")) < stale]
    if todo:
        print(f"Checking job boards for {len(todo)} companies...")
        for name, (ats, slug) in sources.find_boards(todo).items():
            boards[name] = {"ats": ats or "none", "slug": slug or "", "checked": date.today().isoformat(),
                            "note": "" if ats else "no public Greenhouse/Lever/Ashby feed (Workday or own site)"}
    boards = {n: boards[n] for n in names if n in boards}
    BOARDS_FILE.write_text("# Generated by applyme.py: which public job feed each company uses.\n" +
                           yaml.safe_dump(boards, sort_keys=False), encoding="utf-8")
    return boards


def notify(summary, cfg):
    """Discord plugs in here later (Phase 3b): post the summary to #applyme via DISCORD_WEBHOOK_URL in .env."""
    if cfg.get("tracking", {}).get("discord", {}).get("enabled"):
        print("(Discord is not built yet; that's Phase 3b.)")


def last_run(con):
    return con.execute("SELECT * FROM runs WHERE finished IS NOT NULL ORDER BY id DESC LIMIT 1").fetchone()


def build_outputs(con, cfg, run, summary):
    filters.reclassify_all(con, cfg)
    path, n_new, n_all = report.write_html(con, cfg, run, summary)
    csv_path, n_csv = report.write_csv(con, HERE / cfg.get("tracking", {}).get("daily_csv_export", "tracker.csv"))
    return path, n_new, n_all, csv_path, n_csv


def ingest(cfg, con, force_verify=False, use_ai=True):
    run_time = db.now()
    run_id = con.execute("INSERT INTO runs(started) VALUES (?)", (run_time,)).lastrowid
    con.commit()
    boards = load_boards(force_verify)
    ok, failed, downloaded = [], [], []

    print("Downloading the SimplifyJobs / Pitt CSC internship list...")
    try:
        items = sources.fetch_simplify()
        downloaded += items
        ok.append("simplify")
        print(f"  {len(items)} open listings")
    except Exception as e:
        failed.append(f"SimplifyJobs: {e}")

    with_feed = [(n, b["ats"], b["slug"]) for n, b in boards.items() if b["ats"] != "none"]
    print(f"Downloading {len(with_feed)} company job boards...")
    skipped_non_intern = 0
    for name, result in sources.fetch_boards(with_feed).items():
        b = boards[name]
        if isinstance(result, Exception):
            failed.append(f"{name} ({b['ats']}:{b['slug']}): {result}")
            continue
        ok.append(f"{b['ats']}:{b['slug']}")
        interns = [p for p in result if filters.INTERN_RE.search(p["title"])]
        skipped_non_intern += len(result) - len(interns)
        downloaded += interns
        print(f"  {name}: {len(result)} jobs, {len(interns)} internship/co-op")

    new = 0
    for p in downloaded:
        p["dedupe_key"] = sources.make_key(p["company_name"], p["title"], p["locations"])
        new += db.upsert_posting(con, p, run_time)
    for name, b in boards.items():
        db.company_id(con, name, ats=b["ats"], slug=b["slug"], in_companies_txt=1, note=b.get("note", ""))
    gone = db.mark_missing_inactive(con, ok, run_time)
    con.commit()

    ranked = None
    if use_ai and cfg.get("scoring", {}).get("auto", True):
        print()
        ranked = rank.run(con, cfg, HERE)
        print()

    run = {"started": run_time}
    no_feed = [n for n, b in boards.items() if b["ats"] == "none"]
    summary = {
        "Postings downloaded (internships/co-ops)": len(downloaded),
        "New roles added to the database": new,
        "No longer listed (marked inactive)": gone,
        "Sources that worked": f"{len(ok)} (SimplifyJobs + {len(ok) - ('simplify' in ok)} company boards)",
        "Sources that failed": "; ".join(failed) or "none",
        "Companies with no public feed (their roles still come in through SimplifyJobs when listed)":
            ", ".join(no_feed) or "none",
    }
    if ranked:
        summary["Roles scored by Claude this run"] = f"{ranked['scored']} (${ranked['cost']:.4f})"
    path, n_new, n_all, csv_path, n_csv = build_outputs(con, cfg, run, summary)
    summary["Open roles in scope"] = n_all
    summary["New in scope this run"] = n_new
    con.execute("UPDATE runs SET finished=?, summary=? WHERE id=?", (db.now(), json.dumps(summary), run_id))
    con.commit()
    # Write the report again so the counts above appear in it.
    report.write_html(con, cfg, run, summary)
    notify(summary, cfg)

    print("\n=== ApplyMe summary ===")
    for k, v in summary.items():
        print(f"- {k}: {v}")
    print(f"\nReport:  {path.resolve()}\nTracker: {csv_path} ({n_csv} rows)")
    return path


def ask(prompt, default=""):
    shown = f" [{default}]" if default else ""
    try:
        v = input(f"{prompt}{shown}: ").strip()
    except EOFError:
        v = ""
    return v or default


def add_posting(con, cfg, raw_url):
    """Add a posting Ali found himself. Public pages are read to pre-fill; login sites are never fetched."""
    url = sources.clean_url(raw_url)
    row = con.execute("SELECT id, company_name, title FROM postings WHERE url=?", (url,)).fetchone()
    if row:
        print(f"Already in the database as #{row['id']}: {row['company_name']} - {row['title']}")
        return
    pre = {}
    if fetch.never_fetch(url):
        print("This site needs a login or doesn't allow automated reading, so it is not downloaded. "
              "Please type the details.")
    else:
        print("Reading the public page...")
        page = fetch.fetch(con, url)
        if page["status"] == 200 and (page.get("title") or page["useful"]):
            pre = page
            print(f"  Found: {page.get('title') or '?'} ({len(page.get('text') or '')} characters of description)")
        else:
            print(f"  Could not read it ({page['method']}). Please type the details.")
    print("Press Enter to keep the value in [brackets].")
    company = ask("Company", pre.get("company", ""))
    title = ask("Job title", pre.get("title", ""))
    if not company or not title:
        print("Company and title are needed. Nothing was added.")
        return
    location = ask('Location (e.g. "Detroit, MI" or "Remote")', pre.get("location", ""))
    term = ask('Term or dates (e.g. "Summer 2027", "Fall 2027 co-op"; Enter if not stated)')
    text = pre.get("text", "") if pre.get("useful") else ""
    if not text:
        print("Paste the job description if you have it (it makes the flags and score accurate).")
        print("Finish with a line containing only END (or just type END to skip):")
        lines = []
        while True:
            try:
                line = input()
            except EOFError:
                break
            if line.strip() == "END":
                break
            lines.append(line)
        text = "\n".join(lines).strip()
    p = {"source": "manual", "url": url, "company_name": company, "title": title,
         "locations": [location] if location else [], "terms": [term] if term else [],
         "description": (f"Term: {term}\n" if term else "") + text, "date_posted": date.today().isoformat()}
    p["dedupe_key"] = sources.make_key(company, title, p["locations"])
    if not db.upsert_posting(con, p, db.now()):
        con.commit()
        r = con.execute("SELECT id FROM postings WHERE dedupe_key=?", (p["dedupe_key"],)).fetchone()
        print(f"This role is already in the database{f' as #{r[0]}' if r else ''} (same company, title, place).")
        return
    if text:
        con.execute("UPDATE postings SET desc_source='manual' WHERE url=?", (url,))
    con.commit()
    filters.reclassify_all(con, cfg)
    r = con.execute("SELECT * FROM postings WHERE url=?", (url,)).fetchone()
    print(f"Added as #{r['id']}: {company} - {title}")
    print(f"  Location: {r['location_reason']}   Term: {r['term'] or 'not stated'}   "
          f"Flags: {', '.join(json.loads(r['flags'] or '[]')) or 'none'}")
    if r["in_scope"]:
        print("  In scope. It will be scored on the next 'python applyme.py rank' (or ingest).")
    else:
        print(f"  Not in your current scope ({r['exclude_reason']}). It is stored but hidden from the report.")


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    args = sys.argv[1:]
    if not args or args[0] in ("-h", "--help", "help"):
        print(__doc__)
        return
    cfg = load_config()
    con = db.connect(HERE / cfg.get("tracking", {}).get("database", "applyme.db"))
    cmd = args[0]
    if cmd == "ingest":
        path = ingest(cfg, con, use_ai="--no-ai" not in args)
        if "--no-open" not in args:
            webbrowser.open(path.resolve().as_uri())
    elif cmd == "report":
        run = last_run(con)
        summary = json.loads(run["summary"]) if run else {}
        path, n_new, n_all, csv_path, n_csv = build_outputs(con, cfg, run, summary)
        print(f"Open roles in scope ({cfg['location']['scope']}): {n_all}  (new in last ingest: {n_new})")
        print(f"Report:  {path.resolve()}\nTracker: {csv_path} ({n_csv} rows)")
        if "--no-open" not in args:
            webbrowser.open(path.resolve().as_uri())
    elif cmd == "rank":
        limit = int(args[args.index("--limit") + 1]) if "--limit" in args else None
        rank.run(con, cfg, HERE, limit=limit, dry_run="--dry-run" in args)
        run = last_run(con)
        path, *_ = build_outputs(con, cfg, run, json.loads(run["summary"]) if run else {})
        print(f"Report: {path.resolve()}")
    elif cmd == "letter" and len(args) >= 2 and args[1].isdigit():
        letters.make_letter(con, cfg, HERE, int(args[1]))
    elif cmd == "add" and len(args) >= 2:
        add_posting(con, cfg, args[1])
    elif cmd == "spend":
        print(budget.summary_text(con, cfg))
    elif cmd == "browser":
        from autofill import browser
        started = browser.start(cfg)
        print("ApplyMe Chrome is " + ("now open." if started else "already open.") +
              "\nFirst time: sign in to Google in that window yourself (ApplyMe never types passwords)."
              "\nClose the window when you're done for the day.")
    elif cmd == "open":
        from autofill import runner
        n = int(args[1]) if len(args) > 1 and args[1].isdigit() else 5
        runner.open_roles(con, cfg, HERE, n, dry_run="--dry-run" in args, refill="--refill" in args,
                          include_unsupported="--include-unsupported" in args)
    elif cmd == "approve" and len(args) >= 2 and args[1].isdigit():
        row = con.execute("SELECT cover_letter_path FROM applications WHERE posting_id=?", (int(args[1]),)).fetchone()
        if not row or not row["cover_letter_path"]:
            print(f"#{args[1]} has no cover letter draft yet. Run: python applyme.py letter {args[1]}")
        else:
            con.execute("UPDATE applications SET letter_approved=1, updated_at=? WHERE posting_id=?",
                        (db.now(), int(args[1])))
            con.commit()
            print(f"Approved: {row['cover_letter_path']}\nAutofill will attach it when you open #{args[1]}.")
    elif cmd == "answers":
        if len(args) >= 4 and args[1] == "fix" and args[2].isdigit():
            con.execute("UPDATE answer_cache SET answer_json=?, source='ali', is_guess=0 WHERE id=?",
                        (json.dumps(" ".join(args[3:])), int(args[2])))
            con.commit()
            print(f"Answer #{args[2]} updated.")
        else:
            rows = con.execute("SELECT id, label, answer_json, source, is_guess, used FROM answer_cache "
                               "ORDER BY id").fetchall()
            if not rows:
                print("No saved answers yet.")
            for r in rows:
                print(f"#{r['id']:<4} [{r['source']}{', guess' if r['is_guess'] else ''}, used {r['used']}x] "
                      f"{r['label'][:70]}\n       -> {json.loads(r['answer_json'])}")
    elif cmd == "verify":
        boards = load_boards(force=True)
        for name, b in boards.items():
            n = con.execute("SELECT COUNT(*) FROM postings p JOIN companies c ON c.id=p.company_id "
                            "WHERE c.norm=? AND p.active=1", (db.norm_company(name),)).fetchone()[0]
            feed = f"{b['ats']}:{b['slug']}" if b["ats"] != "none" else "NO public feed"
            print(f"{name:28} {feed:28} {n} open internship rows in database")
    elif cmd == "mark" and len(args) >= 3:
        try:
            db.set_status(con, int(args[1]), args[2], " ".join(args[3:]) or None)
            print(f"Posting #{args[1]} is now '{args[2]}'.")
        except ValueError as e:
            print(f"Could not update: {e}")
    else:
        print(__doc__)


if __name__ == "__main__":
    main()
